#include <stdio.h>

// Рекурсивная функция подсчёта единиц в двоичном представлении числа
int count_ones(int n) {
    // Базовый случай: если число равно 0, единиц нет
    if (n == 0) {
        return 0;
    }
    // Рекурсивный случай: младший бит (n % 2) + количество единиц в остальной части (n / 2)
    return (n % 2) + count_ones(n / 2);
}

int main() {
    int N;
    //printf("Введите натуральное число: ");
    scanf("%d", &N);

    printf("%d", count_ones(N));
    return 0;
}
