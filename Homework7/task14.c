#include <stdio.h>

// Рекурсивно считывает последовательность до 0 и выводит нечётные числа.
// is_first — флаг, равен 1, если текущее выводимое число будет первым
// (тогда перед ним не нужно печатать пробел).
void print_odd(int is_first) {
    int x;
    if (scanf("%d", &x) != 1) return;  // конец ввода (на случай отсутствия 0)
    if (x == 0) return;                // встретили завершающий ноль — выход из рекурсии

    if (x % 2 != 0) {                  // число нечётное
        if (!is_first) {
            printf(" ");
        }
        printf("%d", x);
        is_first = 0;                  // следующие числа уже не первые
    }

    print_odd(is_first);               // обрабатываем следующее число
}

int main() {
    print_odd(1);   // начинаем с флагом «первое выводимое число»
    printf("\n");
    return 0;
}
