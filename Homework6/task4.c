#include <stdio.h>

// Описать функцию вычисления f(x) по формуле:
// f(x)= x*x при -2 ≤ x < 2;
// x*x+4x+5 при x ≥ 2;
// 4 при x < -2.
// Используя эту функцию для n заданных чисел, вычислить f(x). Среди вычисленных значений найти наибольшее.

//Формат входных данных:Последовательность не нулевых целых чисел, в конце последовательности число 0.
//Формат результата:Одно целое число


int f(int x) {
    if (x >= -2 && x < 2)
        return x * x;
    else if (x >= 2)
        return x * x + 4 * x + 5;
    else
        return 4;
}

int main() {
    int x, y, max;
    int first = 1;  // флаг, что ещё нет вычисленных значений

    while (scanf("%d", &x) == 1 && x != 0) {
        y = f(x);          // однократное вычисление
        if (first) {
            max = y;
            first = 0;
        } else if (y > max) {
            max = y;
        }
    }

    // Если были введены числа (не сразу 0), выводим максимум
    if (!first)
        printf("%d\n", max);

    return 0;
}

