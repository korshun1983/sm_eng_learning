#include <stdio.h>

/**
 * Проверяет, расположены ли цифры числа n строго по возрастанию.
 * Возвращает 1 (истина), если каждая следующая цифра больше предыдущей,
 * иначе 0 (ложь). Однозначные числа считаются возрастающими.
 */
int grow_up(int n) {
    if (n < 10) return 1;   // 0..9 – подходят

    while (n >= 10) {
        int last = n % 10;              // последняя цифра
        int prev = (n / 10) % 10;       // предпоследняя
        if (prev >= last)               // если не строгое возрастание
            return 0;
        n /= 10;                        // отбрасываем последнюю цифру
    }
    return 1;
}

int main() {
    int n;
    scanf("%d", &n);
    
    if (grow_up(n))
        printf("YES\n");
    else
        printf("NO\n");
    
    return 0;
}
