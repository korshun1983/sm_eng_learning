#include <stdio.h>

/**
 * Преобразует символ цифры в соответствующее целое число.
 * Если символ не является цифрой, возвращает 0 (но в нашей программе
 * эта функция вызывается только для цифр).
 */
int digit_to_num(char c) {
    return c - '0';   // так как c гарантированно в диапазоне '0'..'9'
}

int main() {
    char c;
    int sum = 0;

    // Читаем символы до точки (точку не учитываем)
    while ((c = getchar()) != '.') {
        if (c >= '0' && c <= '9') {
            sum += digit_to_num(c);
        }
    }

    printf("%d\n", sum);

    return 0;
}
